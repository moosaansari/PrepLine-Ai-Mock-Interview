def get_questions(role: str, difficulty: str = 'balanced'):
    questions = QUESTION_BANK.get(role)
    if not questions:
        questions = QUESTION_BANK['Software Engineer']

    level = (difficulty or 'balanced').lower()
    if level in {'beginner', 'easy'}:
        return [q for q in questions if q['difficulty'] == 'Beginner']
    if level in {'intermediate', 'medium'}:
        return [q for q in questions if q['difficulty'] == 'Intermediate']
    if level in {'advanced', 'hard'}:
        return [q for q in questions if q['difficulty'] == 'Advanced']
    return questions

def get_interview_questions(role: str, difficulty: str = 'balanced', limit: int = 8):
    questions = get_questions(role, difficulty)
    return questions[:max(1, min(limit, 8))]
